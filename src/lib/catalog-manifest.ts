export function getManifestImageForSku(sku?: string | null): string | null {
  if (!sku) return null;
  const normalized = sku.toUpperCase().trim();
  return KNOWN_CATALOG_IMAGES[normalized] || null;
}

export function getManifestImageByTitle(title?: string | null): string | null {
  if (!title) return null;
  const clean = title.trim();
  const lower = clean.toLowerCase();
  
  if (TITLE_IMAGE_MAP[clean]) return TITLE_IMAGE_MAP[clean];
  if (TITLE_IMAGE_MAP[lower]) return TITLE_IMAGE_MAP[lower];
  
  // Partial search
  for (const [key, url] of Object.entries(TITLE_IMAGE_MAP)) {
    if (lower.includes(key) || key.includes(lower)) {
      return url;
    }
  }
  return null;
}
